import assert from "node:assert/strict";
import { chromium } from "playwright";
import { promises as fs } from "node:fs";
import path from "node:path";
import { apiOk, appRoot, cleanupAll, makeProject, startServer } from "../tests/helpers.mjs";

let browser;
const lineStart = process.platform === "darwin" ? "Meta+ArrowLeft" : "Home";
const lineEnd = process.platform === "darwin" ? "Meta+ArrowRight" : "End";
try {
  const source = "\uFEFF# Fictional review\r\n\r\nA __bold__ &amp; cautious 😀 claim.\r\n\r\n| A | B |\r\n| --- | --- |\r\n| old | exact |\r\n\r\nMath: $\\ce{H2O}$.\r\n\r\n<div>Keep HTML</div>\r\n";
  const project = await makeProject({ files: { "first.md": source, "second.md": "# Second\n\nPlain text.\n" }, setupArgs: ["--main", "first.md"] });
  const token = "fictional-plate-review-token";
  const server = await startServer(project.root, { env: { MARGIN_MCP_TOKEN: token } });
  browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  const external = [];
  page.on("pageerror", (error) => { errors.push(error.message); console.error(error.message); });
  page.on("request", (request) => { if (!request.url().startsWith(server.baseUrl)) external.push(request.url()); });
  await page.goto(server.baseUrl);
  await page.waitForFunction(() => document.querySelector("#document").dataset.path === "first.md");
  await page.locator("#edit-rich").click();
  await page.waitForSelector(".rich-content[contenteditable=true]");
  assert.equal((await apiOk(server, "/api/document?path=first.md")).source, source);
  assert.equal(await page.locator("#save-rich").isDisabled(), true);
  assert.equal(await page.locator(".rich-source-block svg").count() > 0, true);
  const paragraph = page.locator(".rich-content > p").filter({ hasText: "cautious" });
  await paragraph.evaluate((element) => {
    const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
    let text;
    while ((text = walker.nextNode())) if (text.textContent.includes("cautious")) {
      const start = text.textContent.indexOf("cautious");
      const selection = window.getSelection();
      selection.setBaseAndExtent(text, start + 8, text, start);
      break;
    }
  });
  await page.locator("#selection-comment").click();
  assert.equal(await page.locator("#composer-quote").innerText(), "cautious");
  await page.locator("#composer-body").fill("Fictional source-mapped comment.");
  await page.locator("#composer-submit").click();
  await page.waitForSelector("#composer", { state: "hidden" });
  await page.locator("#edit-rich").click();
  await page.waitForSelector(".rich-content");
  await paragraph.click();
  await page.keyboard.press(lineEnd);
  await page.keyboard.insertText(" Added 中文.");
  await page.getByRole("button", { name: "撤销", exact: true }).click();
  assert.doesNotMatch(await paragraph.innerText(), /Added 中文/);
  await page.getByRole("button", { name: "重做", exact: true }).click();
  assert.match(await paragraph.innerText(), /Added 中文/);
  await page.waitForFunction(() => !document.querySelector("#save-rich").disabled);
  await page.locator('[data-view="original"]').click();
  await page.locator('[data-view="current"]').click();
  assert.match(await paragraph.innerText(), /Added 中文/);
  page.once("dialog", (dialog) => dialog.dismiss());
  await page.locator("#document-select").selectOption("second.md");
  assert.equal(await page.locator("#document-select").inputValue(), "first.md");
  await page.locator("#save-rich").click();
  await page.waitForSelector("#rich-document", { state: "hidden" });
  const updated = source.replace("claim.", "claim. Added 中文.");
  assert.equal((await apiOk(server, "/api/document?path=first.md")).source, updated);
  await page.locator("#edit-rich").click();
  await page.waitForSelector(".rich-content");
  await page.evaluate(() => { document.querySelector("#toast").hidden = true; });
  const cell = page.locator(".rich-content td").filter({ hasText: /^old$/ });
  await cell.click();
  await page.keyboard.press(lineStart);
  await page.keyboard.press(`Shift+${lineEnd}`);
  await page.keyboard.insertText("new");
  await page.locator("#save-rich").click();
  await page.waitForSelector("#rich-document", { state: "hidden" });
  assert.equal((await apiOk(server, "/api/document?path=first.md")).source, updated.replace("old |", "new |"));
  await page.locator("#edit-rich").click();
  await page.waitForSelector(".rich-content");
  assert.equal(await page.locator(".rich-content mark").count() > 0, true);
  await paragraph.evaluate((element) => {
    const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
    let text;
    while ((text = walker.nextNode())) if (text.textContent.includes("cautious")) {
      const start = text.textContent.indexOf("cautious");
      window.getSelection().setBaseAndExtent(text, start, text, start + 8);
      break;
    }
  });
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await page.getByRole("button", { name: "斜体", exact: true }).click();
  await page.locator("#save-rich").click();
  await page.waitForSelector("#rich-document", { state: "hidden" });
  assert.equal((await apiOk(server, "/api/document?path=first.md")).source, updated.replace("old |", "new |").replace("cautious", "_cautious_"));
  await page.locator("#edit-rich").click();
  await page.waitForSelector(".rich-content");
  await fs.mkdir(path.join(appRoot, "docs/images"), { recursive: true });
  await page.evaluate(() => { document.querySelector("#toast").hidden = true; });
  await page.screenshot({ path: path.join(appRoot, "docs/images/plate-editor-light.png"), animations: "disabled" });
  await page.locator("#theme").click();
  await page.screenshot({ path: path.join(appRoot, "docs/images/plate-editor-dark.png"), animations: "disabled" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(appRoot, "docs/images/plate-editor-mobile.png"), animations: "disabled" });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await paragraph.click();
  await page.keyboard.press(lineEnd);
  const cdp = await page.context().newCDPSession(page);
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await cdp.send("Input.imeSetComposition", { text: "输入法", selectionStart: 3, selectionEnd: 3 });
  await cdp.send("Input.insertText", { text: "输入法" });
  await page.waitForFunction(() => document.querySelector(".rich-content").textContent.includes("输入法"));
  assert.match(await paragraph.innerText(), /输入法/);
  const current = await apiOk(server, "/api/document?path=first.md");
  await apiOk(server, "/mcp", { method: "POST", headers: { Authorization: `Bearer ${token}` }, body: { jsonrpc: "2.0", id: 1, method: "tools/call", params: { name: "review_suggest", arguments: { path: "first.md", etag: current.etag, start: current.source.indexOf("cautious"), end: current.source.indexOf("cautious") + 8, text: "qualified", body: "Fictional incoming review." } } } });
  assert.match(await paragraph.innerText(), /输入法/);
  assert.equal((await apiOk(server, "/api/document?path=first.md")).source, current.source);
  await apiOk(server, "/api/review/save", { method: "POST", body: { path: "first.md", etag: current.etag, text: current.source + "\r\nExternal edit.\r\n" } });
  await page.locator("#save-rich").click();
  await page.waitForFunction(() => !document.querySelector("#save-rich").disabled);
  assert.match(await paragraph.innerText(), /输入法/);
  assert.match((await apiOk(server, "/api/document?path=first.md")).source, /External edit/);
  assert.doesNotMatch((await apiOk(server, "/api/document?path=first.md")).source, /输入法/);
  page.once("dialog", (dialog) => dialog.accept());
  await page.locator("#close-rich").click();
  await page.locator("#reload").click();
  await page.waitForFunction(() => document.querySelector("#document").textContent.includes("External edit"));
  await page.locator("#document-select").selectOption("second.md");
  await page.waitForFunction(() => document.querySelector("#document").dataset.path === "second.md");
  await page.locator("#edit-rich").click();
  const plain = page.locator(".rich-content > p").filter({ hasText: "Plain" });
  await plain.click();
  await page.keyboard.press(lineStart);
  for (let i = 0; i < 5; i += 1) await page.keyboard.press("Shift+ArrowRight");
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  page.once("dialog", (dialog) => dialog.accept("https://example.invalid"));
  await page.getByRole("button", { name: "链接", exact: true }).click();
  assert.equal(await page.locator('.rich-content a[href="https://example.invalid"]').innerText(), "Plain");
  await page.locator("#save-rich").click();
  await page.waitForSelector("#rich-document", { state: "hidden" });
  assert.equal((await apiOk(server, "/api/document?path=second.md")).source, "# Second\n\n[Plain](https://example.invalid) text.\n");
  await page.locator("#edit-rich").click();
  await plain.click();
  await page.keyboard.press(lineEnd);
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await plain.evaluate((element) => {
    const clipboard = new DataTransfer();
    clipboard.setData("text/plain", " <unsafe>");
    clipboard.setData("text/html", '<img src="https://example.invalid/remote.png">');
    element.dispatchEvent(new ClipboardEvent("paste", { bubbles: true, cancelable: true, clipboardData: clipboard }));
  });
  assert.match(await plain.innerText(), /<unsafe>/);
  await page.getByRole("button", { name: "表格", exact: true }).click();
  await page.waitForSelector(".rich-content table");
  await page.locator(".rich-content td").first().click();
  await page.keyboard.insertText("Column");
  await page.getByRole("button", { name: "添加行", exact: true }).click();
  assert.equal(await page.locator(".rich-content tr").count(), 3);
  await page.locator("#save-rich").click();
  await page.waitForSelector("#rich-document", { state: "hidden" });
  const composed = (await apiOk(server, "/api/document?path=second.md")).source;
  assert.match(composed, /Column/);
  assert.match((await apiOk(server, "/api/document?path=second.md")).blocks.map((block) => block.display).join(""), /<unsafe>/);
  assert.doesNotMatch(composed, /remote.png/);
  assert.deepEqual(errors, []);
  assert.deepEqual(external, []);
  console.log("Plate editor passed: exact source, draft navigation, text/Chinese/emoji input, tables, MathJax/HTML fallback and local rendering.");
} finally {
  await browser?.close();
  await cleanupAll();
}
